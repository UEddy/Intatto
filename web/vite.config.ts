import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import react from "@vitejs/plugin-react";
import type { Plugin } from "vite";
import { defineConfig } from "vitest/config";
import { NETWORKS } from "./src/config/networks.ts";
import { WALLET_CONNECT_SRC, WALLET_FRAME_SRC, WALLET_IMG_SRC } from "./src/wallet/csp.ts";

/**
 * Where the site is served from: "/Intatto/" on GitHub Pages (a project site, the default), "/" on
 * Cloudflare Pages (INTATTO_BASE=/ npm run build). Routes are hash-based, so no rewrites are needed.
 */
const BASE = process.env.INTATTO_BASE ?? "/Intatto/";
if (!BASE.startsWith("/") || !BASE.endsWith("/")) throw new Error(`INTATTO_BASE must start and end with "/": ${BASE}`);

/**
 * The content security policy. GitHub Pages cannot set headers, so the policy is a <meta> tag,
 * and it is inserted by boot.js, the first script on the page, together with a nonce that is
 * random on every page load:
 *
 * - near-connect runs each wallet's executor as inline script in a sandboxed srcdoc iframe, which
 *   inherits this policy. The inline scripts carry the nonce (near-connect's `cspNonce`); nothing
 *   else can, because the nonce exists only in this page load's memory, never in served HTML.
 * - connect-src is derived from the network configs plus the wallet backends that were measured
 *   (src/wallet/csp.ts, THREAT_MODEL.md "Frontend"), and 'self' for the passkey executor this site
 *   serves (public/wallets/).
 *
 * On Cloudflare Pages the same policy is also sent as a real header (_headers, emitted below),
 * where frame-ancestors works, which a <meta> policy cannot do. A static header cannot carry the
 * per-load nonce, so its script-src allows 'self' and inline scripts; the <meta> policy still
 * requires the nonce, and a script must pass both.
 *
 * Production builds only: the dev server injects inline scripts for hot reload.
 */
function csp(): Plugin {
  const origins = new Set<string>(WALLET_CONNECT_SRC);
  for (const n of Object.values(NETWORKS)) {
    for (const url of [n.rpcUrl, n.archivalRpcUrl, n.indexers.fastnear, n.indexers.nearblocks]) origins.add(new URL(url).origin);
  }
  const directives = (scriptSrc: string) => [
    "default-src 'none'",
    `script-src ${scriptSrc}`,
    // near-connect's popup and the executors' srcdoc documents use inline <style> without a nonce.
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self'",
    `img-src 'self' data: ${WALLET_IMG_SRC.join(" ")}`,
    `connect-src 'self' ${[...origins].sort().join(" ")}`,
    `frame-src ${WALLET_FRAME_SRC.join(" ")}`,
    "manifest-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "object-src 'none'",
  ];
  const policy = directives("'self' 'nonce-{NONCE}'").join("; ");
  const headerPolicy = [...directives("'self' 'unsafe-inline'"), "frame-ancestors 'none'"].join("; ");
  // Cloudflare Pages headers, for every path. Not used by GitHub Pages, which ignores _headers.
  const headers = `# Generated by vite.config.ts. Cloudflare Pages: real HTTP headers for every response.
/*
  Content-Security-Policy: ${headerPolicy}
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: publickey-credentials-get=(self), publickey-credentials-create=(self), camera=(), microphone=(), geolocation=(), usb=(), bluetooth=(), hid=(), serial=(), payment=()
`;
  const boot = (withCsp: boolean) => `// Generated by vite.config.ts. Runs before any other script on the page.
(function () {
  ${
    withCsp
      ? `var bytes = new Uint8Array(18);
  crypto.getRandomValues(bytes);
  var nonce = btoa(String.fromCharCode.apply(null, bytes));
  var meta = document.createElement("meta");
  meta.httpEquiv = "Content-Security-Policy";
  meta.content = ${JSON.stringify(policy)}.replace("{NONCE}", nonce);
  document.head.prepend(meta);
  Object.defineProperty(window, "__INTATTO_CSP_NONCE__", { value: nonce });`
      : `Object.defineProperty(window, "__INTATTO_CSP_NONCE__", { value: undefined });`
  }
  try {
    var t = localStorage.getItem("intatto.theme");
    if (t === "light" || t === "dark") document.documentElement.setAttribute("data-theme", t);
  } catch (e) {}
})();
`;
  return {
    name: "intatto-csp",
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        if (req.url?.split("?")[0] !== `${BASE}boot.js`) return next();
        res.setHeader("Content-Type", "text/javascript");
        res.end(boot(false));
      });
    },
    // `vite preview` of the Cloudflare build (INTATTO_BASE=/) sends the built _headers on every
    // response, as Cloudflare Pages does, so a preview runs under the real header CSP as well as
    // the <meta> one. The GitHub Pages build is previewed without headers, as GitHub serves it.
    configurePreviewServer(server) {
      if (BASE !== "/") return;
      const file = resolve(server.config.root, server.config.build.outDir, "_headers");
      const sent: [string, string][] = [];
      for (const line of readFileSync(file, "utf8").split("\n")) {
        const m = /^\s+([A-Za-z-]+):\s*(.+)$/.exec(line);
        if (m) sent.push([m[1]!, m[2]!]);
      }
      if (!sent.some(([name]) => name === "Content-Security-Policy")) throw new Error(`${file} has no Content-Security-Policy`);
      server.middlewares.use((_req, res, next) => {
        for (const [name, value] of sent) res.setHeader(name, value);
        next();
      });
    },
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "boot.js", source: boot(true) });
      this.emitFile({ type: "asset", fileName: "_headers", source: headers });
    },
  };
}

export default defineConfig({
  base: BASE,
  plugins: [react(), csp()],
  // No data: URIs for assets: the CSP allows fonts and images from this origin only.
  build: { target: "es2023", sourcemap: true, assetsInlineLimit: 0 },
  test: {
    environment: "jsdom",
    include: ["src/**/*.test.{ts,tsx}"],
    setupFiles: ["src/test/setup.ts"],
  },
});
